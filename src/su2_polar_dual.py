@lru_cache(maxsize=3)
def weyl_chamber_masks(name):
    """Exact orbit W.rho, returned as bitmasks of the roots g with <w rho, g> > 0.

    s_v(x) = x - 2<x,v>v maps G to G (s_v(g) = -v conj(g) v), so G is a root
    system and W is finite; W acts simply transitively on chambers, and rho lies
    in an open chamber (asserted), so the orbit has one point per chamber.
    Coordinates are kept as integers: x = X/64 with X in Z[sqrt d]^4.
    """
    _check_group(name)
    d = FIELD[name]
    roots = integer_pair_group(name)          # (a,b) pairs meaning (a+b sqrt d)/4
    mirrors = []
    for v in roots:
        if tuple((-a, -b) for a, b in v) not in mirrors:
            mirrors.append(v)

    def reflect(X, V):
        p = sum(xa*va+d*xb*vb for (xa, xb), (va, vb) in zip(X, V))
        r = sum(xa*vb+xb*va for (xa, xb), (va, vb) in zip(X, V))
        out = []
        for (xa, xb), (va, vb) in zip(X, V):
            ta, tb = p*va+d*r*vb, p*vb+r*va          # (X.V) V ; must be divisible by 8
            if ta % 8 or tb % 8:
                raise ArithmeticError('Unexpected denominator in the Weyl orbit')
            out.append((xa-ta//8, xb-tb//8))
        return tuple(out)

    start = tuple((64*c, 0) for c in RHO)
    for V in mirrors:
        p = sum(xa*va for (xa, _), (va, _) in zip(start, V))
        r = sum(xa*vb for (xa, _), (_, vb) in zip(start, V))
        if surd_sign(p, r, d) == 0:
            raise ArithmeticError('rho lies on a mirror')
    seen = {start}
    frontier = [start]
    while frontier:
        nxt = []
        for X in frontier:
            for V in mirrors:
                Y = reflect(X, V)
                if Y not in seen:
                    seen.add(Y)
                    nxt.append(Y)
        frontier = nxt
    masks = []
    for X in seen:
        mask = 0
        for i, g in enumerate(roots):
            p = sum(xa*ga+d*xb*gb for (xa, xb), (ga, gb) in zip(X, g))
            r = sum(xa*gb+xb*ga for (xa, xb), (ga, gb) in zip(X, g))
            sg = surd_sign(p, r, d)
            if sg == 0:
                raise ArithmeticError('An orbit point lies on a mirror')
            if sg > 0:
                mask |= 1 << i
        masks.append(mask)
    return len(seen), tuple(masks)


def chamber_count(name, indices):
    """N = number of W-chambers inside the polar dual {x : <x, v_i> >= 0}."""
    order, masks = weyl_chamber_masks(name)
    need = 0
    for i in indices:
        need |= 1 << i
    return order, sum(1 for m in masks if m & need == need)


