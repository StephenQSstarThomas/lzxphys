"""Li2-free exact volumes of tetrahedra whose vertices lie in 2T, 2O or 2I.

For a nondegenerate spherical tetrahedron T with polar dual T*,

    vol T + vol T* = pi^2 + 1/2 sum_e l_e th_e - pi/2 sum_e l_e      (Schlaefli),

every edge length l_e is a rational multiple of pi (p_i^{-1} p_j has finite
order), and T* is cut out by mirrors v^perp, v in G, of the finite reflection
group W generated by x -> -v conj(x) v.  Hence vol T* = N * 2 pi^2/|W| with N an
exact chamber count.  Every dihedral angle th_e is reduced, by certified
double/complement/sum identities in Q(sqrt d), to rational multiples of pi plus a
Q-combination of a fixed basis: none (2T), arctan(1/sqrt 2) (2O), and
arctan(1/2), arctan(1/sqrt 5), arctan(sqrt 15) (2I).

The result is the SAME geometric volume as the Murakami Li2 formula (no change of
representative).  No floating point is used: all signs are decided exactly in
Q(sqrt d).  Proof: docs/review-0923/SU2_POLAR_DUAL_EXACT.md.
"""
from copy import deepcopy
from fractions import Fraction
from functools import lru_cache
from itertools import combinations
from math import isqrt

import sympy as s
from su2_exact_ade import classify_group, integer_pair_group
from su2_symbolic import EDGE_PAIRS, exact_level, unit_quaternion

FIELD = {'2T': 0, '2O': 2, '2I': 5}
# tan^2 of the basis angles (all rational); the basis angle is arctan(sqrt(T)).
BASIS_TAN2 = {'2T': (), '2O': (Fraction(1, 2),),
              '2I': (Fraction(1, 4), Fraction(1, 5), Fraction(15))}
RHO = (7, 3, 2, 1)   # generic point: checked below to lie on no mirror


class Surd:
    """Exact a + b sqrt(d), a and b rational, d in {0, 2, 5}."""
    __slots__ = ('a', 'b', 'd')

    def __init__(self, a, b=0, d=0):
        self.a, self.b, self.d = Fraction(a), Fraction(b), d
        if d == 0 and self.b:
            raise ValueError('sqrt(0) part must vanish')

    def _c(self, o):
        return o if isinstance(o, Surd) else Surd(o, 0, self.d)

    def __add__(self, o):
        o = self._c(o)
        return Surd(self.a+o.a, self.b+o.b, self.d)
    __radd__ = __add__

    def __sub__(self, o):
        o = self._c(o)
        return Surd(self.a-o.a, self.b-o.b, self.d)

    def __rsub__(self, o):
        return self._c(o)-self

    def __neg__(self):
        return Surd(-self.a, -self.b, self.d)

    def __mul__(self, o):
        o = self._c(o)
        return Surd(self.a*o.a+self.d*self.b*o.b, self.a*o.b+self.b*o.a, self.d)
    __rmul__ = __mul__

    def norm(self):
        return self.a*self.a-self.d*self.b*self.b

    def __truediv__(self, o):
        o = self._c(o)
        n = o.norm()
        if n == 0:
            raise ZeroDivisionError('Division by zero in Q(sqrt d)')
        return self*Surd(o.a/n, -o.b/n, self.d)

    def __rtruediv__(self, o):
        return self._c(o)/self

    def __eq__(self, o):
        o = self._c(o)
        return self.a == o.a and self.b == o.b

    def __hash__(self):
        return hash((self.a, self.b))

    def sign(self):
        return surd_sign(self.a, self.b, self.d)

    def __lt__(self, o):
        return (self-o).sign() < 0

    def __gt__(self, o):
        return (self-o).sign() > 0

    def key(self):
        return (self.a, self.b)

    def sympy(self):
        return s.Rational(self.a.numerator, self.a.denominator) \
            + s.Rational(self.b.numerator, self.b.denominator)*s.sqrt(self.d)

    def __repr__(self):
        return f'Surd({self.a}, {self.b}, {self.d})'


def surd_sign(a, b, d):
    """Exact sign of a + b sqrt(d)."""
    sa = (a > 0)-(a < 0)
    sb = (b > 0)-(b < 0)
    if sb == 0 or d == 0:
        return sa
    if sa == 0 or sa == sb:
        return sa or sb
    c = a*a-d*b*b
    return sa if c > 0 else sb if c < 0 else 0


def _rational_sqrt(f):
    f = Fraction(f)
    if f < 0:
        return None
    n, m = isqrt(f.numerator), isqrt(f.denominator)
    return Fraction(n, m) if n*n == f.numerator and m*m == f.denominator else None


def surd_sqrt(x):
    """Exact nonnegative square root in Q(sqrt d), or None if it does not exist."""
    if x.sign() < 0:
        return None
    if x.sign() == 0:
        return Surd(0, 0, x.d)
    if x.b == 0:
        r = _rational_sqrt(x.a)
        if r is not None:
            return Surd(r, 0, x.d)
        r = _rational_sqrt(x.a/x.d) if x.d else None
        return Surd(0, r, x.d) if r is not None else None
    n = _rational_sqrt(x.norm())
    if n is None:
        return None
    for sign in (1, -1):
        u = _rational_sqrt((x.a+sign*n)/2)
        if u:
            for c in (Surd(u, x.b/(2*u), x.d), Surd(-u, -x.b/(2*u), x.d)):
                if c*c == x and c.sign() > 0:
                    return c
    return None


def _check_group(name):
    if name not in FIELD:
        raise ValueError('Use 2T, 2O, or 2I')


@lru_cache(maxsize=3)
def group_vectors(name):
    """Unit quaternions of the group as exact Surd 4-tuples (same order as su2_exact_ade)."""
    _check_group(name)
    d = FIELD[name]
    return tuple(tuple(Surd(Fraction(a, 4), Fraction(b, 4), d) for a, b in q)
                 for q in integer_pair_group(name))


@lru_cache(maxsize=3)
def _index(name):
    return {tuple(x.key() for x in v): i for i, v in enumerate(group_vectors(name))}


def dot(u, v):
    total = u[0]*v[0]
    for x, y in zip(u[1:], v[1:]):
        total = total+x*y
    return total


def quaternion_product(left, right):
    """Negative-cross convention of su2_symbolic, on Surd coordinates."""
    a, x, y, z = left
    b, u, v, w = right
    return (a*b-x*u-y*v-z*w, a*u+b*x-y*w+z*v, a*v+b*y-z*u+x*w, a*w+b*z-x*v+y*u)


def _det3(m):
    return (m[0][0]*(m[1][1]*m[2][2]-m[1][2]*m[2][1])
            - m[0][1]*(m[1][0]*m[2][2]-m[1][2]*m[2][0])
            + m[0][2]*(m[1][0]*m[2][1]-m[1][1]*m[2][0]))


def cofactor(m, i, j):
    minor = [[m[r][c] for c in range(4) if c != j] for r in range(4) if r != i]
    value = _det3(minor)
    return value if (i+j) % 2 == 0 else -value


def determinant(vectors):
    """det of the 4x4 matrix whose columns are the given vectors."""
    rows = [[v[r] for v in vectors] for r in range(4)]
    return sum((rows[0][j]*cofactor(rows, 0, j) for j in range(4)), Surd(0, 0, vectors[0][0].d))


