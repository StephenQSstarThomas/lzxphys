def _as_indices(name, vertices):
    index = _index(name)
    points = group_vectors(name)
    out = []
    for v in vertices:
        if isinstance(v, int) and not isinstance(v, bool):
            if not 0 <= v < len(points):
                raise ValueError('Group index out of range')
            out.append(v)
            continue
        q = unit_quaternion(v)
        key = tuple(_surd_from_sympy(x, FIELD[name]).key() for x in q)
        if key not in index:
            raise ValueError('An input is not a member of '+name)
        out.append(index[key])
    return tuple(out)


def _surd_from_sympy(x, d):
    """Exact coordinates in Q(sqrt d) by algebraic rewriting only (no nsimplify)."""
    x = s.expand(s.radsimp(s.expand(s.sympify(x))))
    if d:
        b = x.coeff(s.sqrt(d))
        a = s.expand(x-b*s.sqrt(d))
    else:
        a, b = x, s.Integer(0)
    if not (a.is_Rational and b.is_Rational):
        raise ValueError('Coordinate outside Q(sqrt d)')
    return Surd(Fraction(int(a.p), int(a.q)), Fraction(int(b.p), int(b.q)), d)


def tetrahedron_volume(name, vertices, k=1):
    """Exact Li2-free volume of the tetrahedron spanned by four group elements.

    V = a pi^2 + (pi/2) sum_j b_j Theta_j with rational a, b_j (actual volume in
    (0, pi^2), not only modulo 2 pi^2). Orientation is sgn det(vertices).
    """
    _check_group(name)
    k = exact_level(k)
    idx = _as_indices(name, vertices)
    points = group_vectors(name)
    P = [points[i] for i in idx]
    det = determinant(P)
    if det.sign() == 0:
        raise ValueError('Degenerate tetrahedron: use the global chain')
    G, dihedral = dihedral_data(P)
    order, N = chamber_count(name, idx)
    nb = len(BASIS_TAN2[name])
    edges = []
    a = 1-Fraction(2*N, order)
    b = [Fraction(0)]*nb
    for i, j in EDGE_PAIRS:            # user order (01,02,03,23,13,12)
        q = edge_fraction(G[i][j])
        sign, c2 = dihedral[(min(i, j), max(i, j))]
        r, c = dihedral_angle(name, sign, c2)
        a += (q*r-q)/2
        for t in range(nb):
            b[t] += q*c[t]
        edges.append({'edge': (i, j), 'length_over_pi': q, 'dihedral_sign': sign,
                      'dihedral_cos2': c2.sympy(), 'dihedral': (r, c)})
    theta = basis_symbols(name)
    volume = s.Rational(a.numerator, a.denominator)*s.pi**2 \
        + s.pi/2*sum((s.Rational(x.numerator, x.denominator)*t for x, t in zip(b, theta)), s.S.Zero)
    orientation = det.sign()
    exponent = s.Rational(a.numerator, a.denominator)*s.pi \
        + sum((s.Rational(x.numerator, x.denominator)*t for x, t in zip(b, theta)), s.S.Zero)/2
    return {'group': name, 'indices': idx, 'orientation': orientation,
            'chambers': N, 'weyl_order': order, 'edges': tuple(edges),
            'rational_part': a, 'basis_coefficients': tuple(b),
            'basis': theta, 'volume': volume, 'oriented_volume': orientation*volume,
            'rational_volume': not any(b),
            'phase': s.exp(-s.I*k*orientation*exponent),
            'method': 'polar dual + Schlaefli + Coxeter chambers (same tetrahedron)'}


def polar_formula(name, g1, g2, g3, k=1):
    """Three group elements -> cumulative vertices (1, g1, g1g2, g1g2g3) -> exact phase."""
    _check_group(name)
    points = group_vectors(name)
    index = _index(name)
    i1, i2, i3 = _as_indices(name, (g1, g2, g3))
    one = index[tuple(Surd(x, 0, FIELD[name]).key() for x in (1, 0, 0, 0))]
    p2 = quaternion_product(points[i1], points[i2])
    p3 = quaternion_product(p2, points[i3])
    j2, j3 = index[tuple(x.key() for x in p2)], index[tuple(x.key() for x in p3)]
    return tetrahedron_volume(name, (one, i1, j2, j3), k=k)


@lru_cache(maxsize=3)
def _catalogue(name):
    rows = []
    for t in classify_group(name)['types']:
        r = tetrahedron_volume(name, t['representative_indices'])
        rows.append({'gram_key': t['gram_key'], 'anchored_multiplicity': t['anchored_multiplicity'],
                     'representative_indices': t['representative_indices'],
                     'chambers': r['chambers'], 'rational_part': r['rational_part'],
                     'basis_coefficients': r['basis_coefficients'],
                     'rational_volume': r['rational_volume'], 'volume': r['volume']})
    order, _ = weyl_chamber_masks(name)
    return {'group': name, 'weyl_order': order, 'basis_tan2': BASIS_TAN2[name],
            'basis': basis_symbols(name), 'types': tuple(rows)}


